/** Shared API client for Sentinel SOC v4 */
export const API = import.meta.env.VITE_SENTINEL_API ?? "http://127.0.0.1:8000";
export const API_KEY = import.meta.env.VITE_SENTINEL_KEY ?? "sentinel-dev-key";

const ANALYST_KEY = "sentinel_analyst";

export function getAnalyst() {
  return localStorage.getItem(ANALYST_KEY) || "alice";
}

export function setAnalyst(id) {
  localStorage.setItem(ANALYST_KEY, id);
}

export function headers(extra = {}) {
  return {
    "X-API-Key": API_KEY,
    "X-Analyst": getAnalyst(),
    "Content-Type": "application/json",
    ...extra,
  };
}

export async function api(path, opts = {}) {
  const r = await fetch(`${API}${path}`, {
    ...opts,
    headers: { ...headers(), ...(opts.headers || {}) },
  });
  if (!r.ok) {
    const err = await r.text();
    throw new Error(err || r.statusText);
  }
  if (r.status === 204) return null;
  return r.json();
}

