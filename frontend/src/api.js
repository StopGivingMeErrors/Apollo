/**
 * Provenance badge for an event or alert. "unlabelled" covers rows written
 * before provenance tracking existed — they are not claimed as either.
 */
export function sourceTag(source) {
  if (source === "simulator") return { label: "SIM", cls: "sim", title: "Generated by the built-in attack simulator" };
  if (source === "mixed") return { label: "MIX", cls: "mixed", title: "Fed by both real and simulated events" };
  if (source === "unlabelled" || source == null) return { label: "—", cls: "unknown", title: "Recorded before provenance tracking; origin unknown" };
  return { label: "REAL", cls: "real", title: "Observed by a honeypot sensor" };
}

export function fmtTime(iso) {
  if (!iso) return "—";
  try {
    return new Date(iso.endsWith("Z") ? iso : iso + "Z").toLocaleString();
  } catch {
    return iso;
  }
}

export function fmtDuration(seconds) {
  if (seconds == null) return "—";
  if (seconds < 60) return `${Math.round(seconds)}s`;
  if (seconds < 3600) return `${Math.round(seconds / 60)}m`;
  return `${(seconds / 3600).toFixed(1)}h`;
}
